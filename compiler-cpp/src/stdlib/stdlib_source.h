// Port of stdlib/StdlibSource.kt (and its macOS actuals): the standard
// library as a tree of `.az` files with a package manifest beside it.
#pragma once

#include <optional>
#include <string>
#include <vector>

namespace azora {

/** One standard-library source file: its path relative to the `std/` root, and its text. */
struct StdlibFile {
    std::string path;
    std::string source;
};

/** A resolved standard library: where it came from, what version it claims, and its files. */
struct StdlibTree {
    std::string origin;
    std::string version;
    std::vector<StdlibFile> files;
};

/** The package manifest beside a `std/` root. */
inline const char* const STDLIB_PACKAGE_MANIFEST = "package.azon";

/** The standard-library fields read from `package.azon`. */
struct StdlibPackageManifest {
    std::string name;
    std::string version;
};

/** Reads `package.name` and `package.version` from AZON, tolerant of everything else. */
std::optional<StdlibPackageManifest> parseStdlibPackageManifest(const std::string& source);

/** A candidate root, why it was considered, and whether the user named it. */
struct StdlibRoot {
    std::string path;
    std::string origin;
    bool explicit_ = false;
};

/** Candidate `std/` roots on this platform, most specific first. */
std::vector<StdlibRoot> stdlibDiskRoots();

/** Every `.az` file under [root], paths relative with `/`, sorted; nullopt when not a directory. */
std::optional<std::vector<StdlibFile>> readStdlibTree(const std::string& root);

/** `package.azon` beside a stdlib root, or nullopt when absent. */
std::optional<std::string> readStdlibPackageManifest(const std::string& root);

/** The standard library bundled into the compiler (generated by tools/embed-std.sh). */
const std::string& stdlibBundleManifest();
const std::vector<StdlibFile>& stdlibBundleFiles();

}  // namespace azora
