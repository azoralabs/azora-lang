package org.azora.lang.codegen

import kotlin.test.Test
import kotlin.test.assertEquals

/**
 * Binary operators on a const-generic pack. The Engine's `Vec<T, N>` declares
 * `oper+ &.(rhs: Self&)`, `oper+ &.(rhs: T&)` and the unary `oper+ &.()`; the
 * parser keys the binary ones by their written operand (`oper+@Vec`,
 * `oper+@T`), a specialization never re-keyed them, and `p + q` on a
 * `Vec<Double, 3>` fell back to the bare - unary - member: `p + q` was `p` and
 * `p - q` was `-p` (2026-11-20). A literal operand (`p * 2.0`) missed the
 * `Double` overload the same way, and the scalar-on-the-left operators,
 * generated by a top-level `inline for`, had their field loop's `${"$"}{f.name}`
 * folded by the outer loop into `rhs.f.name`.
 */
class ConstGenericOperatorExecTest {
    private val program = """
        import std.io
        import std.reflection

        pack Vec<T, N: Int> where T is Number && N in 2..4 {
            var x: T = 0
            var y: T = 0
            var z: T = 0 where N >= 3
            var w: T = 0 where N == 4
        }

        impl Vec<T, N> {
            oper+ &.(rhs: Self&): Self = Self(inline for f in reflect<Self>.fields { self.${"$"}{f.name} + rhs.${"$"}{f.name} })
            oper+ &.(rhs: T&): Self = Self(inline for f in reflect<Self>.fields { self.${"$"}{f.name} + rhs })
            oper- &.(rhs: Self&): Self = Self(inline for f in reflect<Self>.fields { self.${"$"}{f.name} - rhs.${"$"}{f.name} })
            oper- &.(rhs: T&): Self = Self(inline for f in reflect<Self>.fields { self.${"$"}{f.name} - rhs })
            oper* &.(rhs: Self&): Self = Self(inline for f in reflect<Self>.fields { self.${"$"}{f.name} * rhs.${"$"}{f.name} })
            oper* &.(rhs: T&): Self = Self(inline for f in reflect<Self>.fields { self.${"$"}{f.name} * rhs })
            oper/ &.(rhs: Self&): Self = Self(inline for f in reflect<Self>.fields { self.${"$"}{f.name} / rhs.${"$"}{f.name} })
            oper/ &.(rhs: T&): Self = Self(inline for f in reflect<Self>.fields { self.${"$"}{f.name} / rhs })
            oper+= !.(rhs: Self&): Unit {
                inline for f in reflect<Self>.fields { self.${"$"}{f.name} += rhs.${"$"}{f.name} }
            }
            oper+= !.(rhs: T&): Unit {
                inline for f in reflect<Self>.fields { self.${"$"}{f.name} += rhs }
            }
            oper+ &.(): Self = self
            oper- &.(): Self where T is SignedNumber = Self(inline for f in reflect<Self>.fields { -self.${"$"}{f.name} })
        }

        inline for Ty in [Int, Double] {
            oper*<N: Int> Ty&.(rhs: Vec<Ty, N>&): Vec<Ty, N> where N in 2..4 {
                return Vec<Ty, N>(inline for f in reflect<Vec<Ty, N>>.fields { self * rhs.${"$"}{f.name} })
            }
        }

        typealias Vec2 = Vec<Double, 2>
        typealias Vec3 = Vec<Double, 3>
        typealias Vec4 = Vec<Double, 4>
        typealias Vec3i = Vec<Int, 3>

        func show(v: Vec3) { println("${"$"}{v.x} ${"$"}{v.y} ${"$"}{v.z}") }

        func main() {
            fin p = Vec3(1.0, 2.0, 3.0)
            fin q = Vec3(10.0, 20.0, 30.0)
            fin h: Double = 0.5
            show(p + q)
            show(p - q)
            show(p * q)
            show(q / p)
            show(p + h)
            show(p - 1.0)
            show(p * 2.0)
            show(q / 2)
            show(-p)
            show(h * p)
            show(2.0 * p)
            show(p + q * 2.0)
            var acc = Vec3(0.0, 0.0, 0.0)
            acc += p
            acc += 1.0
            show(acc)
            fin a = Vec2(1.0, 2.0) + Vec2(3.0, 5.0)
            println("${"$"}{a.x} ${"$"}{a.y}")
            fin m = Vec4(1.0, 2.0, 3.0, 4.0) - Vec4(4.0, 3.0, 2.0, 1.0)
            println("${"$"}{m.x} ${"$"}{m.y} ${"$"}{m.z} ${"$"}{m.w}")
            fin i = 3 * (Vec3i(1, 2, 3) + Vec3i(4, 5, 6))
            println("${"$"}{i.x} ${"$"}{i.y} ${"$"}{i.z}")
        }
    """.trimIndent()

    private val expected = listOf(
        "11.0 22.0 33.0",
        "-9.0 -18.0 -27.0",
        "10.0 40.0 90.0",
        "10.0 10.0 10.0",
        "1.5 2.5 3.5",
        "0.0 1.0 2.0",
        "2.0 4.0 6.0",
        "5.0 10.0 15.0",
        "-1.0 -2.0 -3.0",
        "0.5 1.0 1.5",
        "2.0 4.0 6.0",
        "21.0 42.0 63.0",
        "2.0 3.0 4.0",
        "4.0 7.0",
        "-3.0 -1.0 1.0 3.0",
        "15 21 27",
    ).joinToString("\n")

    @Test fun llvmChoosesTheBinaryOverload() {
        for (optimized in listOf(false, true)) {
            assertEquals(expected, LlvmExec.run(program, optimized).trim(), "optimized=$optimized")
        }
    }

    @Test fun webAssemblyChoosesTheBinaryOverload() {
        if (!WasmExec.available) return
        assertEquals(expected, WasmExec.run(program).trim())
    }
}
