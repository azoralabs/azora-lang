#!/bin/sh
# embed-std.sh <azora-lang dir> <out.cpp>: the standard library bundled into
# the compiler (CPP_PORT_PLAN.md §5), as Kotlin's generated AzStdlibBundle:
# every std/**/*.az in path order, and the package.azon beside std/.
set -e
root=$1
out=$2
tmp="$out.tmp"
cr=$(printf '\r')

# A file's bytes as a C++ string literal of exactly its size.
literal() {
    size=$(wc -c < "$1" | tr -d ' ')
    printf 'std::string(\n'
    sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e "s/$cr/\\\\r/g" -e 's/^/"/' -e 's/$/\\n"/' "$1"
    printf ', %s)' "$size"
}

{
    echo '// Generated by tools/embed-std.sh from std/ and package.azon. Do not edit.'
    echo '#include "stdlib/stdlib_source.h"'
    echo
    echo 'namespace azora {'
    echo
    echo 'const std::string& stdlibBundleManifest() {'
    printf '    static const std::string manifest = '
    literal "$root/package.azon"
    echo ';'
    echo '    return manifest;'
    echo '}'
    echo
    echo 'const std::vector<StdlibFile>& stdlibBundleFiles() {'
    echo '    static const std::vector<StdlibFile> files = {'
    (cd "$root/std" && find . -name '*.az' -type f | sed 's|^\./||' | LC_ALL=C sort) | while IFS= read -r path; do
        printf '        StdlibFile{"%s", ' "$path"
        literal "$root/std/$path"
        echo '},'
    done
    echo '    };'
    echo '    return files;'
    echo '}'
    echo
    echo '}  // namespace azora'
} > "$tmp"
mv "$tmp" "$out"
