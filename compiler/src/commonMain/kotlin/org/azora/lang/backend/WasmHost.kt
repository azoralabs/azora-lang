package org.azora.lang.backend

/**
 * The host side of a module the WebAssembly backend compiles, generated with
 * it (TARGETS_DIP §4): JavaScript that supplies every `env` import the module
 * declares, so a browser or Node runs it with no hand-written loader.
 *
 * [glue] is a JavaScript function expression:
 *
 * ```js
 * const host = (glue)(write, provided)
 * const { instance } = await WebAssembly.instantiate(bytes, host.imports)
 * host.attach(instance)
 * instance.exports.main()
 * ```
 *
 * `write(text)` receives everything the program prints. The printing imports
 * are implemented here; any other import - a `bridge` the program declares for
 * its host - is taken from `provided` by name, and one the host does not
 * provide throws, naming it, when the program first calls it.
 */
object WasmHost {
    private val IMPORT = Regex("""\(import\s+"env"\s+"((?:[^"\\]|\\.)*)"""")

    /** The `env` imports [wat] declares, in order, as the names the module links by. */
    fun importsOf(wat: String): List<String> = IMPORT.findAll(wat).map { decode(it.groupValues[1]) }.distinct().toList()

    /** A WAT string literal's text: `\xx` is a byte, the rest UTF-8. */
    private fun decode(literal: String): String {
        if ('\\' !in literal) return literal
        val bytes = mutableListOf<Byte>()
        var i = 0
        while (i < literal.length) {
            val c = literal[i]
            if (c != '\\' || i + 1 >= literal.length) {
                c.toString().encodeToByteArray().forEach { bytes += it }
                i++
                continue
            }
            val e = literal[i + 1]
            val simple = mapOf('n' to 0x0A, 't' to 0x09, 'r' to 0x0D, '\\' to 0x5C, '\'' to 0x27, '"' to 0x22)[e]
            if (simple != null) {
                bytes += simple.toByte()
                i += 2
            } else {
                bytes += literal.substring(i + 1, i + 3).toInt(16).toByte()
                i += 3
            }
        }
        return bytes.toByteArray().decodeToString()
    }

    private val PRINTING: Map<String, String> = mapOf(
        "print_i32" to "(x) => write(String(x) + '\\n')",
        "print_i64" to "(x) => write(x.toString() + '\\n')",
        "print_f64" to "(x) => write(float(x) + '\\n')",
        "print_f32" to "(x) => write(float(x) + '\\n')",
        "print_bool" to "(x) => write((x ? 'true' : 'false') + '\\n')",
        "print_str" to "(p) => write(text(p) + '\\n')",
        "write_i32" to "(x) => write(String(x))",
        "write_i64" to "(x) => write(x.toString())",
        "write_f64" to "(x) => write(float(x))",
        "write_f32" to "(x) => write(float(x))",
        "write_bool" to "(x) => write(x ? 'true' : 'false')",
        "write_str" to "(p) => write(text(p))",
    )

    /** The host for a module that declares [imports]. */
    fun glue(imports: List<String>): String = buildString {
        appendLine("(function azoraHost(write, provided) {")
        appendLine("  // Generated by the Azora compiler for this module; do not edit.")
        appendLine("  provided = provided || {}")
        appendLine("  let memory = null")
        appendLine("  const decoder = new TextDecoder()")
        appendLine("  // A String is its byte length, then its UTF-8 bytes.")
        appendLine("  const text = (p) => decoder.decode(new Uint8Array(memory.buffer, p + 4, new DataView(memory.buffer).getInt32(p, true)))")
        appendLine("  const float = (x) => Number.isInteger(x) ? x.toFixed(1) : String(x)")
        appendLine("  const missing = (name) => () => { throw new Error(\"the host provides no '\" + name + \"', which this program imports\") }")
        appendLine("  const env = {")
        for (name in imports) {
            val quoted = jsString(name)
            val printing = PRINTING[name]
            if (printing != null) appendLine("    $quoted: $printing,")
            else appendLine("    $quoted: provided[$quoted] || missing($quoted),")
        }
        appendLine("  }")
        appendLine("  return {")
        appendLine("    imports: { env },")
        appendLine("    attach(instance) { memory = instance.exports.memory },")
        appendLine("    text,")
        appendLine("  }")
        append("})")
    }

    /** [wat]'s host. */
    fun glueFor(wat: String): String = glue(importsOf(wat))

    /**
     * [text] as a JavaScript string literal that cannot end early: everything
     * but letters, digits and `_$.-` is a `\uXXXX` escape. An import's name can
     * be any string (`@foreignName("…")`), and the host is evaluated, so no
     * name may be able to write code into it.
     */
    private fun jsString(text: String): String = buildString {
        append('"')
        for (c in text) {
            if (c in 'a'..'z' || c in 'A'..'Z' || c in '0'..'9' || c in "_$.-") append(c)
            else append("\\u").append(c.code.toString(16).padStart(4, '0'))
        }
        append('"')
    }
}
