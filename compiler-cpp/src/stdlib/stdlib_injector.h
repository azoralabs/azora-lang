// Port of stdlib/StdlibInjector.kt: injects library declarations into a
// compilation unit.
//
// Library symbols are import-gated: a file sees a module's names only after
// importing it. Only the items actually referenced are appended (following
// library references transitively), a user declaration always shadows a
// library item of the same name, and a library declaration the program may
// not name takes a hidden identity (`module__path__Name`).
//
// One struct, as Kotlin's one class, split over stdlib_injector*.cpp; the
// member declarations between MEMBERS BEGIN/END are generated by
// tools/member-decls.py (see tools/stdlib-injector-decls.sh).
//
// Kotlin compares AST values structurally where they sit in sets and lists
// that are deduplicated; this port compares index-owned nodes by identity and
// deduplicates copies by their canonical dump text (ledger rulings).
#pragma once

