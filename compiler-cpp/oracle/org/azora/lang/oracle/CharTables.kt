package org.azora.lang.oracle

/**
 * Writes `compiler-cpp/src/base/char_tables.cpp`: the answers this JVM gives to
 * the Char functions the compiler calls, for all 65,536 UTF-16 units. The C++
 * port reads them instead of guessing at Unicode (CPP_PORT_PLAN.md §6.7).
 */
object CharTables {
    private class Bits(val name: String, val test: (Char) -> Boolean)

    private val properties = listOf(
        Bits("LETTER") { it.isLetter() },
        Bits("DIGIT") { it.isDigit() },
        Bits("LETTER_OR_DIGIT") { it.isLetterOrDigit() },
        Bits("WHITESPACE") { it.isWhitespace() },
        Bits("LOWER_CASE") { it.isLowerCase() },
        Bits("UPPER_CASE") { it.isUpperCase() },
    )

    fun generate(): String = buildString {
        appendLine("// Generated by compiler-cpp/oracle/CharTables.kt from ${System.getProperty("java.vendor")} ${System.getProperty("java.version")}.")
        appendLine("// Do not edit: rerun the oracle's `chars` command.")
        appendLine("#include \"base/chars.h\"")
        appendLine()
        appendLine("namespace azora {")
        appendLine()
        appendLine("namespace {")
        appendLine()
        for (property in properties) {
            appendLine("const uint64_t ${property.name}[1024] = {")
            for (word in 0 until 1024) {
                var bits = 0uL
                for (bit in 0 until 64) {
                    if (property.test((word * 64 + bit).toChar())) bits = bits or (1uL shl bit)
                }
                append("    0x").append(bits.toString(16).padStart(16, '0')).appendLine("ULL,")
            }
            appendLine("};")
            appendLine()
        }
        pairs("UPPER_MAP") { c -> c.uppercaseChar().code.takeIf { it != c.code } }
        pairs("LOWER_MAP") { c -> c.lowercaseChar().code.takeIf { it != c.code } }
        pairs("DIGIT_VALUE") { c -> Character.digit(c, 36).takeIf { it >= 0 } }
        appendLine("bool test(const uint64_t* table, char16_t c) { return (table[c >> 6] >> (c & 63)) & 1; }")
        appendLine()
        appendLine("int lookup(const uint32_t (*table)[2], int count, char16_t c) {")
        appendLine("    int lo = 0, hi = count - 1;")
        appendLine("    while (lo <= hi) {")
        appendLine("        int mid = (lo + hi) / 2;")
        appendLine("        if (table[mid][0] == c) return (int)table[mid][1];")
        appendLine("        if (table[mid][0] < c) lo = mid + 1; else hi = mid - 1;")
        appendLine("    }")
        appendLine("    return -1;")
        appendLine("}")
        appendLine()
        appendLine("}  // namespace")
        appendLine()
        appendLine("bool isLetter(char16_t c) { return test(LETTER, c); }")
        appendLine("bool isDigit(char16_t c) { return test(DIGIT, c); }")
        appendLine("bool isLetterOrDigit(char16_t c) { return test(LETTER_OR_DIGIT, c); }")
        appendLine("bool isWhitespace(char16_t c) { return test(WHITESPACE, c); }")
        appendLine("bool isLowerCase(char16_t c) { return test(LOWER_CASE, c); }")
        appendLine("bool isUpperCase(char16_t c) { return test(UPPER_CASE, c); }")
        appendLine()
        appendLine("char16_t uppercaseChar(char16_t c) {")
        appendLine("    int mapped = lookup(UPPER_MAP, UPPER_MAP_COUNT, c);")
        appendLine("    return mapped < 0 ? c : (char16_t)mapped;")
        appendLine("}")
        appendLine()
        appendLine("char16_t lowercaseChar(char16_t c) {")
        appendLine("    int mapped = lookup(LOWER_MAP, LOWER_MAP_COUNT, c);")
        appendLine("    return mapped < 0 ? c : (char16_t)mapped;")
        appendLine("}")
        appendLine()
        appendLine("int digitValue(char16_t c, int radix) {")
        appendLine("    int value = lookup(DIGIT_VALUE, DIGIT_VALUE_COUNT, c);")
        appendLine("    return value < radix ? value : -1;")
        appendLine("}")
        appendLine()
        appendLine("}  // namespace azora")
    }

    private fun StringBuilder.pairs(name: String, map: (Char) -> Int?) {
        val entries = (0 until 65536).mapNotNull { code -> map(code.toChar())?.let { code to it } }
        appendLine("const int ${name}_COUNT = ${entries.size};")
        appendLine("const uint32_t $name[${entries.size}][2] = {")
        entries.chunked(6).forEach { row ->
            appendLine("    " + row.joinToString(" ") { (k, v) -> "{0x${k.toString(16)}, 0x${v.toString(16)}}," })
        }
        appendLine("};")
        appendLine()
    }
}
